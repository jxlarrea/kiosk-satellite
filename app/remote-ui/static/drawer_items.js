const pluginItem = (pluginId, command) => `plugin:${pluginId}/${command}`;
const isPluginItem = (id) => id.startsWith('plugin:');

export function decodeDrawerItems(raw) {
  try {
    const map = raw ? JSON.parse(raw) : null;
    const ids = (list) => (Array.isArray(list) ? list : []).filter((id) => typeof id === 'string' && id);
    const shown = [...new Set(ids(map?.shown))];
    const hidden = new Set(ids(map?.hidden).filter((id) => !shown.includes(id)));
    return { shown, hidden };
  } catch (_) {
    return { shown: [], hidden: new Set() };
  }
}

function shows(items, id) {
  return items.shown.includes(id) || (!items.hidden.has(id) && !OFF_BY_DEFAULT.has(id));
}

function insertAtDefault(rows, id) {
  if (isPluginItem(id)) {
    let i = 0;
    while (i < rows.length && isPluginItem(rows[i])) i++;
    rows.splice(i, 0, id);
    return;
  }
  for (let i = DRAWER_ITEM_ORDER.indexOf(id) - 1; i >= 0; i--) {
    const before = rows.indexOf(DRAWER_ITEM_ORDER[i]);
    if (before >= 0) { rows.splice(before + 1, 0, id); return; }
  }
  rows.unshift(id);
}

// The rows of [available] the menu shows, in menu order.
function arrange(items, available) {
  const pool = new Set(available);
  const out = items.shown.filter((id) => pool.has(id));
  const order = [...available.filter(isPluginItem), ...DRAWER_ITEM_ORDER.filter((id) => pool.has(id))];
  for (const id of order) {
    if (!out.includes(id) && shows(items, id)) insertAtDefault(out, id);
  }
  return out;
}

// The plugin actions that asked for the drawer, running or not, as the
// device lists them. A stopped plugin keeps its place while it is stopped.
async function pluginActions() {
  try {
    const r = await cmd('getPluginActions');
    return r?.ok && Array.isArray(r.data) ? r.data.filter((a) => a.drawer === true) : [];
  } catch (_) {
    return [];
  }
}

// The names of the built-in rows on, for the row's summary.
export function drawerItemsText(raw) {
  return arrange(decodeDrawerItems(raw), DRAWER_ITEM_ORDER).map((id) => t(NAMES[id])).join(', ');
}

// The picker over every row, the rows on picked in menu order. Resolves to
// the value to save, or null on cancel. [remoteOn] is the device's Remote
// administration switch: while it is off the menu keeps Settings anyway.
export async function openDrawerItemsPicker(raw, remoteOn) {
  const items = decodeDrawerItems(raw);
  const actions = await pluginActions();
  const all = [
    ...actions.map((a) => pluginItem(a.pluginId, a.command)),
    ...DRAWER_ITEM_ORDER,
  ];
  const spec = {
    key: 'drawer_items',
    loader: async () => ({
      items: [
        ...actions.map((a) => ({
          id: pluginItem(a.pluginId, a.command),
          name: t('drawerPluginAction', { pluginName: String(a.pluginName), actionTitle: String(a.title) }),
          iconPath: ICONS.plugin, group: '', available: a.available === true, raw: a,
        })),
        ...DRAWER_ITEM_ORDER.map((id) => ({
          id,
          name: t(NAMES[id]),
          sub: id === 'settings' && !remoteOn ? t('drawerItemsSettingsKept') : null,
          iconPath: ICONS[id], group: '', available: true, raw: {},
        })),
      ],
      notes: {},
    }),
    searchHint: t('drawerItemsSearch'),
    noGroup: '', chips: false, headings: false, byGroupName: false, keep: null,
  };
  const ids = await pickItems({ title: t('settingUiDrawerItemsTitle'), spec, selected: arrange(items, all) });
  if (!ids) return null;
  // Only what was listed is kept, so an action its plugin dropped goes too.
  const hidden = all.filter((id) => !ids.includes(id)).sort();
  return JSON.stringify({ shown: ids, hidden });
}
